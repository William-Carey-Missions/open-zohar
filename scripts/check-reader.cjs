const fs=require('node:fs/promises');
const http=require('node:http');
const path=require('node:path');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
const assert=(v,msg)=>{if(!v)throw Error(msg);};
(async()=>{
 const server=http.createServer(async(req,res)=>{
  try{
   const rel=decodeURIComponent(req.url.split('?')[0]);
   const file=path.resolve(root,'.'+(rel==='/'?'/index.html':rel));
   if(!file.startsWith(root+path.sep))throw Error('path');
   const data=await fs.readFile(file);
   res.setHeader('Content-Type',({'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8','.json':'application/json; charset=utf-8','.woff2':'font/woff2','.svg':'image/svg+xml'})[path.extname(file)]||'application/octet-stream');
   res.end(data);
  }catch{res.statusCode=404;res.end('not found');}
 });
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 let browser;
 try{
  browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const base='http://127.0.0.1:'+server.address().port;
  await page.goto(base+'/#lezen/zohar-i/1a/1');
  await page.waitForSelector('.passage');
  assert(await page.locator('.passage').count()===4,'I 1a heeft vier passages');
  assert((await page.locator('#reader-status').innerText()).includes('Conceptvertaling'),'Conceptstatus ontbreekt');
  assert(await page.locator('.original').first().getAttribute('dir')==='rtl','Grondtekst niet RTL');
  await page.locator('.passage-notes summary').first().click();
  assert((await page.locator('.passage-notes[open]').innerText()).includes('Rabbi Elazar'),'Variantnoot niet zichtbaar');
  await page.evaluate(()=>scrollTo(0,0));
  await fs.mkdir(path.join(root,'.qa'),{recursive:true});
  await page.screenshot({path:path.join(root,'.qa/desktop.png')});
  await page.locator('#next').click();await page.waitForFunction(()=>document.getElementById('chapter-select').value==='1b');
  assert(await page.locator('.passage').count()===8,'I 1b heeft acht passages');
  await page.locator('#previous').click();await page.waitForFunction(()=>document.getElementById('chapter-select').value==='1a');
  await page.locator('#topnav-search-input').fill('roos');await page.locator('#topnav-search-input').press('Enter');
  await page.waitForSelector('#search-results a');
  assert(await page.locator('#search-results a').count()>=3,'Zoeken vindt vertaalde tekst niet');
  await page.goto(base+'/#lezen/zohar-i/3b/1');
  await page.waitForFunction(()=>document.getElementById('chapter-select').value==='3b');
  assert(await page.locator('.passage').count()===7,'I 3b moet alle zeven bronalinea’s tonen');
  assert((await page.locator('#reader-status').innerText()).includes('Volledig bronfolio'),'Volledige brondekking niet vermeld');
  assert(!(await page.locator('#next').isDisabled()),'Vervolg na3b ontbreekt');
  await page.locator('#next').click();await page.waitForFunction(()=>document.getElementById('chapter-select').value==='4a');
  await page.goto(base+'/#lezen/zohar-i/36a');
  await page.waitForFunction(()=>document.getElementById('chapter-select').value==='36a');
  assert(await page.locator('#reader-source a').count()===5,'Beide bronnen van het doorlopende folio ontbreken');
  await page.goto(base+'/#lezen/zohar-i/60a');
  await page.waitForFunction(()=>document.getElementById('chapter-select').value==='60a');
  assert((await page.locator('#reader-source').innerText()).includes('818700'),'Verkeerde bronrevisie bij I 60a');
  assert(await page.locator('.passage-notes').count()===await page.locator('.passage').count(),'Bron is niet per passage toegankelijk');
  assert((await page.locator('#passages h2').allTextContents()).includes('Tosefta'),'Ingebedde Tosefta-tekst ontbreekt');
  await page.goto(base+'/#lezen/zohar-i/80b');
  await page.waitForFunction(()=>document.getElementById('chapter-select').value==='80b');
  assert((await page.locator('#reader-status').innerText()).includes('telt niet mee'),'Onzekere foliodekking wordt niet uitgelegd');
  assert((await page.locator('#passages h2').allTextContents()).includes('Sitre Tora'),'Afzonderlijke Sitre Tora-sectie ontbreekt');
  await page.setViewportSize({width:390,height:844});
  await page.goto(base+'/#lezen/zohar-i/1a/1');await page.waitForFunction(()=>document.getElementById('chapter-select').value==='1a');
  await page.evaluate(()=>scrollTo(0,0));
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobiele horizontale overloop');
  await page.screenshot({path:path.join(root,'.qa/mobile.png')});
  await page.locator('#settings-open').click();await page.locator('#show-original').uncheck();await page.locator('#settings-close').click();
  assert(!(await page.locator('.original').first().isVisible()),'Grondtekstoptie werkt niet');
  await page.locator('#theme-toggle').click();
  await page.reload();await page.waitForSelector('.passage');
  assert(!(await page.locator('.original').first().isVisible()),'Leesvoorkeur niet bewaard');
  await page.selectOption('#mobile-section','bronnen');
  await page.waitForSelector('#bronnen:visible');
  assert((await page.locator('#bronnen').innerText()).includes('167'),'Bronverantwoording ontbreekt');
  await page.selectOption('#mobile-section','inleiding');
  await page.waitForSelector('#inleiding:visible');
  assert((await page.locator('#inleiding h1').innerText())==='Inleiding op de Zohar','Titel inleiding ontbreekt');
  assert((await page.locator('#inleiding').innerText()).includes('opvattingen binnen de tekst'),'Neutrale inleiding ontbreekt');
  assert((await page.locator('#inleiding [data-translation-progress]').innerText()).includes('%'),'Vertaalpercentage ontbreekt');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Inleiding loopt mobiel over');
  await page.screenshot({path:path.join(root,'.qa/inleiding-mobile.png')});
  await page.setViewportSize({width:1280,height:900});
  assert(await page.evaluate(()=>{
    const brand=document.querySelector('.topnav-brand').getBoundingClientRect();
    const nav=document.querySelector('.topnav-links').getBoundingClientRect();
    return brand.right<=nav.left||brand.bottom<=nav.top||nav.bottom<=brand.top;
  }),'Merknaam en navigatie overlappen bij middelbrede vensters');
  await page.setViewportSize({width:1440,height:1000});
  await page.reload();await page.waitForSelector('#inleiding:visible');
  assert(await page.locator('.topnav-links [data-section="inleiding"]').getAttribute('aria-current')==='page','Inleiding niet actief in navigatie');
  await page.screenshot({path:path.join(root,'.qa/inleiding-desktop.png')});
  await page.locator('#inleiding a[href="#lezen/zohar-i/1a/1"]').first().click();
  await page.waitForSelector('#lezen:visible .passage');
  assert((await page.locator('#chapter-select').inputValue())==='1a','Leesroute uit inleiding werkt niet');
  assert(errors.length===0,errors.join('\n'));
  console.log(JSON.stringify({browser:'chromium',desktop:true,mobile:true,search:true,navigation:true,introduction:true,notes:true,sourceCoverage:true,preferences:true,pageErrors:errors.length}));
 }finally{if(browser)await browser.close();await new Promise(resolve=>server.close(resolve));}
})().catch(e=>{console.error(e);process.exitCode=1;});
